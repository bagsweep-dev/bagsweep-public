// Regenerate the UI's SmartAccount creation-code constant from the CURRENT compiled artifact.
// Run `hardhat compile` first, then this. ALWAYS run it as part of a factory deploy: the constant
// must come from the exact build that deploys the target factory (even a functionally identical
// rebuild differs in the trailing metadata digest, which changes accountInitCodeHash). The UI's
// startup guard (assertBytecodeInSync) then verifies keccak256(constant) == factory.accountInitCodeHash.
//   node scripts/gen-ui-bytecode.js
const fs = require("fs");
const path = require("path");

const art = JSON.parse(
  fs.readFileSync(path.join(__dirname, "..", "artifacts/contracts/SmartAccount.sol/SmartAccount.json"), "utf8")
);
const code = art.bytecode;
if (!/^0x[0-9a-fA-F]+$/.test(code)) throw new Error("bad artifact bytecode");

const header = [
  "// SmartAccount creation code (type(SmartAccount).creationCode). DEPLOYMENT-SPECIFIC, not frozen:",
  "// it must equal the accountInitCodeHash of the factory the UI targets (ADDR.factory / VITE_FACTORY).",
  "// Generated by contracts/scripts/gen-ui-bytecode.js from the compiled artifact. Regenerate from",
  "// the exact build that deploys your target factory. The startup guard assertBytecodeInSync() reads",
  "// factory.accountInitCodeHash() and refuses to compute addresses on mismatch (audit v5).",
].join("\n");

const out = `${header}\nimport type { Hex } from "viem";\n\nexport const SMART_ACCOUNT_CREATION_CODE: Hex =\n  "${code}";\n`;
const dst = path.join(__dirname, "..", "..", "protocol-ui", "src", "config", "smartAccountBytecode.ts");
fs.writeFileSync(dst, out);
console.log(`wrote ${dst} (${(code.length - 2) / 2} bytes)`);
